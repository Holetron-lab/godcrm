const column = (column_name, type = 'text', options = {}) => ({
  column_name,
  display_name: options.display || column_name,
  type,
  required: options.required === true,
  ...(options.target ? { target: options.target } : {}),
  config: options.config || null,
});

const table = (key, name, display_name, icon, columns, tableType = null, project = 'main') => ({
  key,
  project,
  name,
  display_name,
  icon,
  table_type: tableType,
  columns: columns.map((entry, order_index) => ({ ...entry, order_index })),
});

const select = (options) => ({
  options: options.map((option) => typeof option === 'object' ? option : { value: option, label: option }),
});

