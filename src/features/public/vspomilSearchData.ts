type LogEvent = {
  type: 'search' | 'confirm' | 'more_variants' | 'not_found' | 'reformulate' | 'lucky_click' | 'find_similar' | 'restart';
  chain_id?: string;
  session_id?: string;
  query?: string;
  results?: Array<{ title: string; title_ru?: string; type: string; confidence: number }>;
  result?: { title: string; title_ru?: string; type: string; confidence: number; position?: number };
  more_count?: number;
  prev_query?: string;
  is_lucky?: boolean;
  mode?: 'initial' | 'more';
};

export const logEvent = (ev: LogEvent) => {
  try {
    const payload = JSON.stringify(ev);
    if (typeof navigator !== 'undefined' && typeof navigator.sendBeacon === 'function') {
      const blob = new Blob([payload], { type: 'application/json' });
      if (navigator.sendBeacon('/api/v3/tools/vspomnil/log', blob)) return;
    }
    fetch('/api/v3/tools/vspomnil/log', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: payload,
      keepalive: true,
    }).catch(() => {});
  } catch { /* Analytics delivery must not interrupt the search interaction. */ }
};

export const newId = () => {
  try {
    if (typeof crypto !== 'undefined' && typeof crypto.randomUUID === 'function') return crypto.randomUUID();
  } catch { /* Fall back to the timestamp-based identifier below if randomUUID is unavailable. */ }
  return `${Date.now()}-${Math.random().toString(36).slice(2, 10)}`;
};
